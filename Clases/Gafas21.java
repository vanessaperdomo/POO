public class Gafas21 {
    String marca;
    String color;
    String tipo;

    public void poner() {
        System.out.println("Te pones las gafas de " + marca + " y de color " + color);
    }

    public void quitar() {
        System.out.println("Te quitas las gafas de " + marca);
    }

    public void limpiar() {
        System.out.println("Limpiando las gafas de " + marca + " y tipo " + tipo);
    }
}
